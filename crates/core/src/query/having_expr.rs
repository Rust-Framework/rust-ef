//! HAVING expression AST: `HavingExpr`, `AggKind`, `CompareOp`.

use crate::provider::DbValue;

use super::ast::BoolExpr;
use super::expr::SqlExpr;

/// Aggregate function kind for `HavingExpr`.
///
/// Used by `linq!(having ...)` when the having clause contains
/// nested boolean expressions (`AND`/`OR`/`NOT`) or aggregate-versus-aggregate
/// comparisons (`COUNT(b.id) > SUM(b.views)`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AggKind {
    Count,
    Sum,
    Avg,
    Min,
    Max,
}

impl AggKind {
    /// Returns the SQL keyword for this aggregate.
    pub fn sql_name(&self) -> &'static str {
        match self {
            AggKind::Count => "COUNT",
            AggKind::Sum => "SUM",
            AggKind::Avg => "AVG",
            AggKind::Min => "MIN",
            AggKind::Max => "MAX",
        }
    }

    /// Parses an aggregate name (case-insensitive).
    pub fn from_name(name: &str) -> Option<Self> {
        match name.to_uppercase().as_str() {
            "COUNT" => Some(AggKind::Count),
            "SUM" => Some(AggKind::Sum),
            "AVG" => Some(AggKind::Avg),
            "MIN" => Some(AggKind::Min),
            "MAX" => Some(AggKind::Max),
            _ => None,
        }
    }
}

/// Comparison operator for `HavingExpr`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CompareOp {
    Eq,
    Ne,
    Gt,
    Ge,
    Lt,
    Le,
}

impl CompareOp {
    /// Returns the SQL operator string.
    pub fn sql_name(&self) -> &'static str {
        match self {
            CompareOp::Eq => "=",
            CompareOp::Ne => "!=",
            CompareOp::Gt => ">",
            CompareOp::Ge => ">=",
            CompareOp::Lt => "<",
            CompareOp::Le => "<=",
        }
    }

    /// Parses a comparison operator from its SQL symbol.
    pub fn from_symbol(symbol: &str) -> Option<Self> {
        match symbol {
            "=" => Some(CompareOp::Eq),
            "!=" => Some(CompareOp::Ne),
            ">" => Some(CompareOp::Gt),
            ">=" => Some(CompareOp::Ge),
            "<" => Some(CompareOp::Lt),
            "<=" => Some(CompareOp::Le),
            _ => None,
        }
    }
}

/// AST node for `HAVING` expressions.
///
/// Supports boolean combinations (`AND`/`OR`/`NOT`) and aggregate-versus-aggregate
/// comparisons in addition to the basic `agg(col) op value` form. Generated by
/// `linq!(having ...)` expansion and compiled to SQL by `to_sql`.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub enum HavingExpr {
    /// `agg(col) op value` — basic comparison against a literal.
    Compare {
        agg: AggKind,
        col: String,
        op: CompareOp,
        value: DbValue,
    },
    /// `expr AND expr`.
    And(Box<HavingExpr>, Box<HavingExpr>),
    /// `expr OR expr`.
    Or(Box<HavingExpr>, Box<HavingExpr>),
    /// `NOT expr`.
    Not(Box<HavingExpr>),
    /// `agg(col1) op agg(col2)` — aggregate-vs-aggregate comparison (no bound parameter).
    CompareAgg {
        left_agg: AggKind,
        left_col: String,
        op: CompareOp,
        right_agg: AggKind,
        right_col: String,
    },
}

impl HavingExpr {
    /// Lowers this HAVING expression into the shared [`BoolExpr`] algebra.
    ///
    /// `HAVING` and `WHERE` then share one compiler and one parameter-order
    /// pipeline (`compile_bool_expr_into`): an aggregate comparison is a
    /// [`BoolExpr::Compare`] between two scalar expressions.
    pub fn into_bool_expr(self) -> BoolExpr {
        match self {
            HavingExpr::Compare {
                agg,
                col,
                op,
                value,
            } => BoolExpr::compare(
                SqlExpr::aggregate(agg, Some(col), false),
                op,
                SqlExpr::literal(value),
            ),
            HavingExpr::CompareAgg {
                left_agg,
                left_col,
                op,
                right_agg,
                right_col,
            } => BoolExpr::compare(
                SqlExpr::aggregate(left_agg, Some(left_col), false),
                op,
                SqlExpr::aggregate(right_agg, Some(right_col), false),
            ),
            HavingExpr::And(left, right) => BoolExpr::And(
                Box::new(left.into_bool_expr()),
                Box::new(right.into_bool_expr()),
            ),
            HavingExpr::Or(left, right) => BoolExpr::Or(
                Box::new(left.into_bool_expr()),
                Box::new(right.into_bool_expr()),
            ),
            HavingExpr::Not(inner) => BoolExpr::Not(Box::new(inner.into_bool_expr())),
        }
    }

    /// Compiles this HAVING expression into a SQL fragment.
    ///
    /// Compatibility helper; the query compiler lowers HAVING to
    /// [`BoolExpr`] and uses the single boolean compiler instead.
    pub fn to_sql(
        &self,
        gen: &dyn crate::provider::ISqlGenerator,
        param_idx: &mut usize,
    ) -> String {
        let mut discarded = Vec::new();
        crate::query::compile::compile_bool_expr_into(
            &self.clone().into_bool_expr(),
            gen,
            param_idx,
            &mut discarded,
        )
    }

    /// Collects bound values in SQL text order.
    pub fn collect_params(&self) -> Vec<DbValue> {
        let mut param_idx = 1usize;
        let mut params = Vec::new();
        let _ = crate::query::compile::compile_bool_expr_into(
            &self.clone().into_bool_expr(),
            &crate::query::compile::PortablePlaceholderGenerator,
            &mut param_idx,
            &mut params,
        );
        params
    }
}
